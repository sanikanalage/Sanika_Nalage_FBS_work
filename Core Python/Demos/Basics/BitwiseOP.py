#& bitwise AND operator
print(10&5)
print(5&3)
print(12&10)
print(129&96)

#| bitwise OR operator
print(12|10)
print(9|2)

#^ bitwise XOR operator
print(12^20)
print(13^9)

#~ bitwise NOR operator
print(~8)
print(~2)

#<< bitwise left shift operator
print(10<<2)
print(12<<1)

#>> bitwise right shift operator
print(6>>1)
print(12>>2)
print(6>>2)